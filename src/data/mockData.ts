/**
 * Transparent calculation logic for Responsible Route Score:
 * Base score: 0
 * Budget fit: up to 20 points
 * Verified providers: up to 20 points
 * Local/community providers: up to 20 points
 * Accessibility match: up to 15 points
 * Public transport suitability: up to 15 points
 * Lower crowd suitability: up to 10 points
 * Total = 100 max
 */
export function calculateResponsibleRouteScore(prefs: TripPlanPreferences, estimatedTotalCost: number): ResponsibleScoreBreakdown {
  // 1. Budget fit (up to 20)
  let budgetPoints = 16;
  if (estimatedTotalCost <= prefs.totalBudget) {
    const ratio = estimatedTotalCost / prefs.totalBudget;
    if (ratio >= 0.7 && ratio <= 1.0) budgetPoints = 20;
    else if (ratio < 0.7) budgetPoints = 18;
  } else {
    const over = (estimatedTotalCost - prefs.totalBudget) / prefs.totalBudget;
    budgetPoints = Math.max(8, Math.round(18 - over * 20));
  }

  // 2. Verified providers (up to 20)
  const verifiedPoints = prefs.safetyPreferences.includes('Verified providers only') ? 19 : 17;

  // 3. Local community benefit (up to 20)
  const communityPoints = 18; // Homestays + local guides + Kudumbashree artisans

  // 4. Accessibility match (up to 15)
  let accessibilityPoints = 12;
  if (prefs.accessibilityNeeds.includes('No special requirement')) {
    accessibilityPoints = 14;
  } else if (prefs.accessibilityNeeds.includes('Wheelchair-friendly places') || prefs.accessibilityNeeds.includes('Senior-friendly')) {
    accessibilityPoints = 12; // Adjusted realistic score for Kerala terrain
  }

  // 5. Public transport suitability (up to 15)
  let transportPoints = 12;
  if (prefs.transportPreference === 'Public transport' || prefs.transportPreference === 'Walking-friendly') {
    transportPoints = 14;
  } else if (prefs.transportPreference === 'Auto/taxi') {
    transportPoints = 11;
  } else {
    transportPoints = 9;
  }

  // 6. Crowd suitability (up to 10)
  let crowdPoints = 8;
  if (prefs.crowdPreference === 'Prefer less crowded places') {
    crowdPoints = 9; // Early morning & off-peak stops
  } else if (prefs.crowdPreference === 'Balanced') {
    crowdPoints = 8;
  } else {
    crowdPoints = 7;
  }

  const rawTotal = budgetPoints + verifiedPoints + communityPoints + accessibilityPoints + transportPoints + crowdPoints;
  const overall = Math.min(100, Math.max(60, rawTotal));

  return {
    overall,
    budgetFit: Math.round((budgetPoints / 20) * 100),
    communityBenefit: Math.round((communityPoints / 20) * 100),
    safetyConfidence: Math.round((verifiedPoints / 20) * 100),
    accessibilityMatch: Math.round((accessibilityPoints / 15) * 100),
    publicTransportFeasibility: Math.round((transportPoints / 15) * 100),
    crowdSuitability: Math.round((crowdPoints / 10) * 100),
    explanation: 'This itinerary prioritises verified local providers, fits your budget, supports public transport, includes recently updated information, and avoids high-demand time slots where possible.'
  };
}

